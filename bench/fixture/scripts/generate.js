// Generates the database client from schema.json into generated/, which is
// not committed: run `npm run generate` after a fresh checkout.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const schema = JSON.parse(readFileSync("schema.json", "utf8"));
const tables = Object.entries(schema)
  .map(([name, columns]) => `  ${name}: ${JSON.stringify(columns)},`)
  .join("\n");
mkdirSync("generated", { recursive: true });
writeFileSync(
  "generated/client.js",
  `// Generated by scripts/generate.js. Do not edit.
export const tables = {
${tables}
};

export function columns(table) {
  const found = tables[table];
  if (found === undefined) throw new Error(\`unknown table: \${table}\`);
  return found;
}
`,
);
console.log("generated/client.js written");
